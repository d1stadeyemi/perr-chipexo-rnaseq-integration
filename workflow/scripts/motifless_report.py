"""motifless_report.py

Compare de novo discovery in the motif-less and motif-positive peak subsets,
and state which interpretation each outcome supports.

THE CONTROL IS THE POINT
  A motif found in the motif-less subset is only informative if it is ABSENT
  from the motif-positive subset. If it appears in both, it is a property of
  PerR-bound regions in general -- or of how the peaks were called -- and says
  nothing about how PerR reaches motif-less sites. Both subsets therefore go
  through the identical pipeline and are reported side by side.

THREE OUTCOMES, THREE READINGS
  a variant of the GBS motif  -> degenerate sites below the FIMO threshold
  a different, subset-specific motif -> second binding mode OR partner factor
  nothing above noise         -> indirect binding, or these peaks are artifacts
"""
import os
import glob

out_md = snakemake.output.md                # noqa: F821
out_tsv = snakemake.output.tsv              # noqa: F821
strains = list(snakemake.params.strains)    # noqa: F821
ML = snakemake.params.mldir                 # noqa: F821
MIN_SEQS = int(snakemake.params.min_seqs)   # noqa: F821
logp = snakemake.log[0]                     # noqa: F821

os.makedirs(os.path.dirname(out_md), exist_ok=True)
os.makedirs(os.path.dirname(logp), exist_ok=True)

SUBSETS = ["motifless", "motifpos"]


def read_split(strain):
    p = os.path.join(ML, strain, f"{strain}.split_summary.tsv")
    d = {}
    if os.path.exists(p):
        with open(p) as fh:
            fh.readline()
            for ln in fh:
                f = ln.rstrip("\n").split("\t")
                if len(f) >= 3:
                    d[f[1]] = int(f[2])
    return d


def read_motifs(strain, subset, top=5):
    p = os.path.join(ML, strain, f"memechip_{subset}", "summary.tsv")
    rows = []
    if not os.path.exists(p):
        return rows
    with open(p) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        i = {c: n for n, c in enumerate(hdr)}
        for ln in fh:
            if ln.startswith("#") or not ln.strip():
                continue
            f = ln.rstrip("\n").split("\t")
            if len(f) < len(hdr):
                continue
            rows.append(dict(
                consensus=f[i.get("CONSENSUS", 4)],
                width=f[i.get("WIDTH", 5)],
                sites=f[i.get("SITES", 6)],
                evalue=f[i.get("E-VALUE", 7)],
                similar=f[i.get("MOST_SIMILAR_MOTIF", 10)] if len(f) > 10 else "",
            ))
    return rows[:top]


def read_tomtom(strain, subset, top=5):
    p = os.path.join(ML, strain, f"tomtom_db_{subset}", "tomtom.tsv")
    rows = []
    if not os.path.exists(p):
        return rows
    with open(p) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        i = {c: n for n, c in enumerate(hdr)}
        for ln in fh:
            if ln.startswith("#") or not ln.strip():
                continue
            f = ln.rstrip("\n").split("\t")
            if len(f) < 6:
                continue
            try:
                q = float(f[i.get("q-value", 5)])
            except (ValueError, IndexError):
                continue
            rows.append((f[0], f[i.get("Target_ID", 1)], q))
    rows.sort(key=lambda x: x[2])
    return rows[:top]


L, W = [], None
L.append("# Motif-less peaks: how does PerR reach them?\n")
L.append("*Auto-generated by `workflow/rules/motifless.smk`.*\n")
L.append("Peaks carrying no GBS PerR motif (FIMO p<1e-4) were subjected to de "
         "novo discovery and compared against 558 curated prokaryotic motifs. "
         "The motif-POSITIVE subset went through the identical pipeline as a "
         "control: a motif present in both subsets is a property of PerR-bound "
         "regions generally, not an explanation for the motif-less ones.\n")

tsv_rows = []
for s in strains:
    sp = read_split(s)
    npos, nneg = sp.get("motifpos", 0), sp.get("motifless", 0)
    tot = npos + nneg
    L.append(f"## {s}\n")
    L.append(f"{nneg} motif-less of {tot} peaks "
             f"({100.0*nneg/tot:.0f}%)" if tot else f"{s}: no peaks")
    if nneg and nneg < MIN_SEQS:
        L.append(f"\n> **UNDERPOWERED.** {nneg} sequences is too few for "
                 "reliable de novo discovery. MEME will return something; treat "
                 "it as descriptive only.\n")
    L.append("")
    for sub in SUBSETS:
        ms = read_motifs(s, sub)
        L.append(f"### {s} — {sub} ({sp.get(sub,0)} peaks)\n")
        if not ms:
            L.append("*No motifs reported.*\n")
        else:
            L.append("| consensus | width | sites | E-value | most similar |")
            L.append("|---|---|---|---|---|")
            for m in ms:
                L.append(f"| `{m['consensus']}` | {m['width']} | {m['sites']} "
                         f"| {m['evalue']} | {m['similar']} |")
            L.append("")
        tt = read_tomtom(s, sub)
        if tt:
            L.append(f"**Database matches (558 curated prokaryotic motifs):**\n")
            L.append("| query | target | q-value |")
            L.append("|---|---|---|")
            for q, t, qv in tt:
                L.append(f"| {q} | {t} | {qv:.3g} |")
            L.append("")
        else:
            L.append("*No database match at the reporting threshold.*\n")
        for m in ms:
            tsv_rows.append([s, sub, sp.get(sub, 0), m["consensus"], m["width"],
                             m["sites"], m["evalue"]])

L.append("## How to read this\n")
L.append("| outcome in the motif-less subset | interpretation |")
L.append("|---|---|")
L.append("| a degenerate variant of TTMTAAATAAG | the motif IS there, below the "
         "FIMO threshold. Not a second mechanism — report as a sensitivity "
         "limitation of the p<1e-4 cutoff. |")
L.append("| a different motif, ABSENT from the motif-positive subset | a second "
         "binding mode, or a partner factor tethering PerR. The strongest "
         "possible outcome. |")
L.append("| a motif present in BOTH subsets | not an explanation. A property of "
         "PerR-bound regions or of the peak-calling. |")
L.append("| nothing above noise | indirect binding with no recoverable sequence "
         "signal, or these peaks are artifacts. Cross-check their ChExMix "
         "subtype and fold enrichment. |")
L.append("")
L.append("**Before calling any database hit a partner factor:** Worsley Hunt & "
         "Wasserman (*Genome Biol* 15:412, 2014) showed a small set of TF motifs "
         "recur as systematic artifacts across hundreds of ChIP datasets. Check "
         "that the hit is not promiscuously enriched, and that it is absent from "
         "the motif-positive control subset.\n")

with open(out_md, "w") as fh:
    fh.write("\n".join(L) + "\n")

with open(out_tsv, "w") as fh:
    fh.write("strain\tsubset\tn_peaks\tconsensus\twidth\tsites\tevalue\n")
    for r in tsv_rows:
        fh.write("\t".join(str(x) for x in r) + "\n")

with open(logp, "w") as lg:
    lg.write(f"strains={strains}  min_seqs={MIN_SEQS}\n")
    for s in strains:
        sp = read_split(s)
        lg.write(f"{s}: motifless={sp.get('motifless',0)} "
                 f"motifpos={sp.get('motifpos',0)}\n")
        for sub in SUBSETS:
            ms = read_motifs(s, sub, top=1)
            if ms:
                lg.write(f"   {sub:10s} top: {ms[0]['consensus']} "
                         f"E={ms[0]['evalue']} sites={ms[0]['sites']}\n")