"""sens_report.py

Turn the per-axis sensitivity tables into a readable verdict: which numbers can
carry a claim, which must be reported with a range, and the sentence to use for
each in the manuscript.

THE DISTINCTION THIS REPORT EXISTS TO DRAW
  A number that does not move across a reasonable parameter grid is a property
  of the DATA. A number that moves is a property of a THRESHOLD. Both can be
  reported -- but not in the same way, and presenting them identically is the
  mistake this analysis is designed to prevent.

  Classification used below:
    INVARIANT   one distinct value across the whole grid
    STABLE      spread <= 15% of the minimum
    SENSITIVE   anything more -- must be reported with its range
"""
import os
import statistics

axes = list(snakemake.params.axes)          # noqa: F821
SENS = snakemake.params.sensdir             # noqa: F821
grids = dict(snakemake.params.grids)        # noqa: F821
out = snakemake.output.md                   # noqa: F821
logp = snakemake.log[0]                     # noqa: F821

os.makedirs(os.path.dirname(out), exist_ok=True)
os.makedirs(os.path.dirname(logp), exist_ok=True)

HEADLINE = [
    ("SHARED_DIRECT", "conserved core (bound + DE in both serotypes)"),
    ("BOUND_BOTH", "conserved cistrome (bound in both serotypes)"),
    ("A909_direct_total", "A909 direct regulon"),
    ("CJB111_direct_total", "CJB111 direct regulon"),
    ("A909_pct_DE_indirect", "% of A909 DEGs that are indirect"),
    ("A909_BOUND_NOT_DE", "A909 bound but not differentially expressed"),
    ("RBH_1to1", "1:1 orthologue pairs"),
]


def read(path):
    if not os.path.exists(path):
        return [], []
    with open(path) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        rows = [dict(zip(hdr, ln.rstrip("\n").split("\t")))
                for ln in fh if ln.strip()]
    return hdr, rows


def nums(rows, key):
    v = []
    for r in rows:
        s = str(r.get(key, "")).strip()
        if s in ("", "None"):
            continue
        try:
            v.append(float(s))
        except ValueError:
            pass
    return v


def verdict(v):
    if not v:
        return "no data", ""
    lo, hi, n = min(v), max(v), len(set(v))
    if n == 1:
        return "INVARIANT", f"{lo:g}"
    if hi <= lo * 1.15:
        return "stable", f"{lo:g} to {hi:g}"
    return "SENSITIVE", f"{lo:g} to {hi:g}"


L = []
W = L.append

W("# Parameter sensitivity\n")
W("*Auto-generated by `workflow/rules/sensitivity.smk`. Regenerated on every "
  "run, so it cannot drift from the tables it summarises.*\n")

W("## Why this exists\n")
W("Every headline number in this study depends on a threshold that was chosen "
  "rather than measured. This analysis re-runs the affected chain across a grid "
  "of alternatives, writing to a parallel tree, and reports which numbers move.\n")
W("**A number that does not move across a reasonable grid is a property of the "
  "data. A number that moves is a property of a threshold.** Both are "
  "reportable; presenting them the same way is not.\n")

W("| classification | meaning | how to report |")
W("|---|---|---|")
W("| **INVARIANT** | one value across the whole grid | report as a plain number |")
W("| stable | spread within 15% | report the value, note the range in methods |")
W("| **SENSITIVE** | wider | **report the value WITH its range** |")
W("")

summary_rows = []

for axis in axes:
    path = os.path.join(SENS, axis, "summary.tsv")
    hdr, rows = read(path)
    if not rows:
        W(f"## {axis}\n\n*No results found at `{path}`.*\n")
        continue

    pk = sorted(next(iter(grids.get(axis, {}) or {{}}.values()), {}).keys()) \
        if grids.get(axis) else []
    if grids.get(axis):
        pk = sorted(next(iter(grids[axis].values())).keys())

    W(f"## Axis: {axis}\n")
    W(f"{len(rows)} combinations. Full table: `{axis}/summary.tsv`\n")
    if pk:
        vals = {k: sorted({str(v[k]) for v in grids[axis].values()}) for k in pk}
        W("Grid: " + " x ".join(f"**{k}** = {', '.join(vals[k])}" for k in pk) + "\n")

    W("| quantity | range | verdict |")
    W("|---|---|---|")
    for key, label in HEADLINE:
        if key not in hdr:
            continue
        v = nums(rows, key)
        vd, rng = verdict(v)
        mark = "**" if vd in ("INVARIANT", "SENSITIVE") else ""
        W(f"| {label} | {rng} | {mark}{vd}{mark} |")
        summary_rows.append((axis, label, rng, vd))
    W("")

    sens = [lab for (a, lab, r, v) in summary_rows if a == axis and v == "SENSITIVE"]
    inv = [lab for (a, lab, r, v) in summary_rows if a == axis and v == "INVARIANT"]
    if inv:
        W(f"**Invariant here:** {', '.join(inv)}. These can be reported as plain "
          "numbers; the grid is evidence they are not artefacts of the setting.\n")
    if sens:
        W(f"**Sensitive here:** {', '.join(sens)}. Report each with its range and "
          "include the grid as a supplementary table.\n")

    if axis == "meme":
        W("**Reading the motif axis.** A wider `maxw` recovering a longer "
          "consensus with comparable or better E-value suggests the production "
          "20 bp cap was truncating the site. A palindromy score approaching 1.0 "
          "would indicate an inverted repeat, i.e. a dimer site. `anr` is the "
          "only occurrence model that can report two copies in one window, which "
          "is what a Fur-family dimer on a 7-1-7 core would produce -- but it "
          "over-reports on AT-rich sequence, so judge the E-value, not the "
          "motif count.\n")

W("## Manuscript sentences\n")
if summary_rows:
    inv_all = sorted({lab for (_, lab, _, v) in summary_rows if v == "INVARIANT"})
    sen_all = sorted({lab for (_, lab, _, v) in summary_rows if v == "SENSITIVE"})
    if inv_all:
        W("For the invariant quantities:\n")
        W("> " + "; ".join(inv_all) + " were unchanged across every parameter "
          "combination tested (Supplementary Table Sx).\n")
    if sen_all:
        W("For the sensitive quantities, give the value and the range:\n")
        for (a, lab, rng, v) in summary_rows:
            if v == "SENSITIVE":
                W(f"> {lab}: report the production value, range {rng} across the "
                  f"{a} grid.\n")
W("")
W("## Reproduce\n")
W("```bash")
W("snakemake --sdm conda -c8 sensitivity_cheap      # seconds")
W("snakemake --sdm conda -c8 sensitivity_moderate   # minutes  (FIMO threshold)")
W("snakemake --sdm conda -c8 sensitivity_motif      # hours    (MEME width/model)")
W("snakemake --sdm conda -c8 sensitivity_peaks      # many hours (ChExMix grid)")
W("```")
W("")
W("`config/config.yaml` is never modified: every combination writes to "
  "`results/11_sensitivity/<axis>/<combo>/`, and the production files are read "
  "but never overwritten.")

with open(out, "w") as fh:
    fh.write("\n".join(L) + "\n")

with open(logp, "w") as lg:
    lg.write(f"axes reported: {axes}\n")
    for a, lab, rng, v in summary_rows:
        lg.write(f"  [{a}] {lab}: {rng}  {v}\n")
