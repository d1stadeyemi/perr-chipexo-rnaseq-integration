"""make_igv_readme.py

Auto-generate results/10_igv/README.md: every file produced, what it is, the
exact load order, the display settings baked into the sessions, and the
interpretation caveats.

Regenerated on every run, so it cannot drift from what the workflow actually
produced -- which is the failure mode of hand-written documentation.
"""
import os, datetime

sessions = list(snakemake.input.sessions)      # noqa: F821
loci = list(snakemake.input.loci)              # noqa: F821
flagship = snakemake.input.flagship            # noqa: F821
out = snakemake.output.md                      # noqa: F821
strains = list(snakemake.params.strains)       # noqa: F821
depths = list(snakemake.params.depths)         # noqa: F821
cfg = dict(snakemake.params.cfg)               # noqa: F821
igvdir = snakemake.params.igvdir               # noqa: F821
refdir = snakemake.params.refdir               # noqa: F821
asm = dict(snakemake.params.assemblies)        # noqa: F821
logp = snakemake.log[0]                        # noqa: F821

os.makedirs(os.path.dirname(out), exist_ok=True)
os.makedirs(os.path.dirname(logp), exist_ok=True)

off = int(cfg.get("offset", 1))
cov = ("5\u2032-end only (the exonuclease stop / crosslink)" if off > 0
       else "full read coverage")

rows = []
try:
    with open(flagship) as fh:
        hdr = fh.readline().rstrip("\n").split("\t")
        i = {c: n for n, c in enumerate(hdr)}
        for ln in fh:
            f = ln.rstrip("\n").split("\t")
            if len(f) >= len(hdr):
                rows.append(f)
except Exception:
    pass

L = []
W = L.append

W(f"# IGV assets — PerR ChIP-exo\n")
W(f"*Auto-generated by `workflow/rules/igv.smk` on "
  f"{datetime.date.today().isoformat()}. Do not edit — regenerated every run.*\n")

W("## Which tracks to use\n")
W("| | `full_depth/` | `depth_matched/` |")
W("|---|---|---|")
W("| Reads | every read | subsampled to a common depth |")
W("| **Use for** | **browsing, and any single-strain figure** | **only figures making an explicit A909-vs-CJB111 claim** |")
W("| Why | maximum sensitivity; nothing is discarded | equal depth so peak counts are comparable |")
W("")
W("**Full depth is the default.** Depth-matching exists to make *peak counts* "
  "comparable between strains; for looking at signal at a locus it discards "
  "~57% of A909's reads and 23 of its 87 events for no benefit. Use it only "
  "when unequal depth would otherwise confound a comparison you are making.\n")

W("## Open a session\n")
W("```")
W("IGV  ->  File  ->  Open Session  ->  <one of the files below>")
W("```")
W("Everything is preconfigured: track order, colours, explicit data ranges, "
  "autoscale off, window function = Maximum.\n")
W("| Session | Contents |")
W("|---|---|")
for s in strains:
    for d in depths:
        W(f"| `session/{s}_{d}.xml` | {s}, {d.replace('_',' ')}, strands stacked |")
        W(f"| `session/{s}_{d}_mirrored.xml` | as above, reverse strand drawn "
          f"below the axis — the canonical ChIP-exo view |")
W("")

W("## Track order in every session\n")
W("| # | Track | Colour | Range |")
W("|---|---|---|---|")
W(f"| 1 | IP forward 5\u2032 | blue | 0–{cfg.get('range_ip',150)} |")
W(f"| 2 | IP reverse 5\u2032 | red | 0–{cfg.get('range_ip',150)} (or −{cfg.get('range_ip',150)}–0 mirrored) |")
W(f"| 3 | no-tag control | grey | 0–{cfg.get('range_ctrl',150)} |")
W("| 4 | ChExMix peaks (full depth) | slate | — |")
W("| 5 | peaks surviving the depth match | slate | — |")
W("| 6 | GBS PerR motif, FIMO p<1e−4 | rust | — |")
W("| 7 | GAS Per box (reference only) | grey-blue | — |")
W("| 8 | direct regulon genes | rust / teal | — |")
W("| 9 | RefSeq genes | dark grey | — |")
W("")
W("**The control track is never omitted.** A peak shown without a flat control "
  "beneath it is not evidence, and it is the first thing a sceptical reader "
  "looks for.\n")

W("## How the coverage was built\n")
W(f"- **Signal**: {cov}. In ChIP-exo the 5\u2032 end of R1 *is* the exonuclease "
  "stop, i.e. the footprint border.")
W("- **Strand split**: R1 only — forward = `--samFlagInclude 64 --samFlagExclude 16`, "
  "reverse = `--samFlagInclude 80`. R2 does not carry the border.")
W(f"- **Bin size**: {cfg.get('binsize',1)} bp. A footprint is tens of bp; binning would smear it.")
W("- **Normalisation**: one CPM-equivalent scale factor computed from the "
  "**unfiltered** merged BAM and applied to both strands.")
W("")
W("> **Why that last point matters.** Asking deepTools for CPM *after* filtering "
  "to one strand computes the scale factor from that subset, so the two strands "
  "land on different scales and the footprint looks asymmetric when it is not. "
  "Sharing one scale factor makes them comparable by construction.\n")

W("## Finding a gene\n")
W("```bash")
for s in strains:
    W(f"grep -i 'YOUR_GENE' {igvdir}/loci/{s}.loci.tsv | cut -f2,3,4,5,11,12")
W("```")
W("Paste `igv_context` (gene ±%d bp — the default view) or `igv_zoom` "
  "(TSS ±%d bp — resolves the strand doublet) into IGV's location box.\n"
  % (cfg.get("flank_context", 750), cfg.get("flank_zoom", 250)))
W("The zoom window centres on the **TSS**, not the gene midpoint: PerR is a "
  "repressor, so the binding that matters is at the promoter — which for "
  "minus-strand genes is the gene *end*.\n")

if rows:
    W("## Curated panels\n")
    W("| # | Panel | Strain | Locus | Context | Zoom |")
    W("|---|---|---|---|---|---|")
    for f in rows:
        W(f"| {f[i['order']]} | {f[i['panel']]} | {f[i['strain']]} | "
          f"`{f[i['locus_or_position']]}` | `{f[i['igv_context']]}` | `{f[i['igv_zoom']]}` |")
    W("")
    W("Full rationale and caveats per panel: `loci/flagship_loci.tsv`, columns "
      "`why_this_panel` and `notes`.\n")

W("## Headless snapshots\n")
W("```bash")
W(f"xvfb-run -a igv.sh --batch {igvdir}/batch/{strains[0]}_full_depth_panels.bat")
W("```")
W("The batch script **loads the session first**, so ranges and colours come "
  "from the XML — batch scripts cannot set those, and loading tracks "
  "individually would silently lose every display setting.\n")

W("## Reading the panels — caveats\n")
W("- **The motif track is empty at *perR*.** Neither peak carries a detectable "
  "Per box. That is a finding, not a broken track.")
W("- **CJB111 looks weaker than A909.** Genuine: half-scale bead/antibody prep, "
  "signal fraction 0.159 vs 0.273. Keep the shared range and say so in the legend.")
W("- **Per-site FIMO q-values are ~0.6–1.0** and must never be quoted. The claim "
  "is co-localization and central enrichment (median offset −2 bp), not per-site "
  "significance.")
W("- **The rRNA-operon peak is annotated, not excluded.** It is the only one of "
  "87 touching any rRNA operon or tRNA, so there is no systematic artefact and "
  "an exclusion list would remove almost nothing while looking like post-hoc "
  "filtering.\n")

W("## Figure legends must state\n")
W("1. Which tracks (depth, 5\u2032-end only, R1 strand-split, CPM-equivalent scaling)")
W("2. **That data ranges are identical across compared panels** — the point "
  "reviewers check")
W("3. That the control is the matched no-tag sample")
W("4. Genome build accessions: " + ", ".join(f"{s} {a}" for s, a in asm.items()))
W("5. Coordinates for every panel\n")

W("## Regenerate\n")
W("```bash")
W("snakemake --sdm conda -c8 igv              # everything")
W("snakemake --sdm conda -c8 igv_full_depth   # full-depth assets only")
W("```")

with open(out, "w") as fh:
    fh.write("\n".join(L) + "\n")

with open(logp, "w") as lg:
    lg.write(f"wrote {out}\n")
    lg.write(f"strains={strains} depths={depths} flagship_panels={len(rows)}\n")
